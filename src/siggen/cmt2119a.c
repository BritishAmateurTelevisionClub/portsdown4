void SetCMT2119AFreq(int64_t Freq)
{
  double DispFreqDouble;

  DispFreqDouble = ((double)(Freq)) / 1000000.0;
  //printf("Setting Freq to %f MHz\n", DispFreqDouble);

  cmtSetDefault();
  cmtSetFrequency(DispFreqDouble);
  cmtUpdate();
}


uint64_t ReadCMT2119AEPROM(void)
{
  uint64_t EEPROMHz;
  double EEPROMFreq;

  cmtReadFromChip();
  digitalWrite(GPIO_SPI_DATA, LOW);

  EEPROMFreq = cmtGetFrequency();
  EEPROMHz = (uint64_t)(EEPROMFreq * 1000000.0);
  //printf("Current EEPROM Frequency is %f MHz or %lld Hz\n", EEPROMFreq, EEPROMHz);
  return EEPROMHz;
}


