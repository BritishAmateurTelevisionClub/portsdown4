void cmtSetDefault(void)
{
  for(int i = 0; i < CMTNUMREGS; i++)
  {
    cmtReg[i] = CMT2119ook[i];
  }
}


void cmtInit(void)
{
  pinMode(GPIO_SPI_CLK, OUTPUT);
  digitalWrite(GPIO_SPI_CLK, HIGH);
  pinMode(GPIO_SPI_DATA, OUTPUT);
  digitalWrite(GPIO_SPI_DATA, HIGH);            // GPIO_SPI_DATA left high as this enables the output. 
}


void CMT2119A_RESET(void)
{
  TWI_reset(); //step 1
  TWI_WRREG(0x3d, 0x01); //step 2 send SOFT_RST
  usleep(2);
  TWI_WRREG(0x0D, 0x02); //step 7 send the TWI_OFF command. Control reverts to simple DAT signals
}


void cmtUpdate(void)
{
  TWI_reset(); //step 1
  TWI_WRREG(0x3d, 0x01); //step 2 send SOFT_RST
  usleep(2);

  //some proprietary command preamble from the datasheet
  TWI_WRREG(0x02, 0x78); //Open LDO & Osc step 3

  TWI_WRREG(0x2F, 0x80); //vActiveRegsister step 4
  TWI_WRREG(0x35, 0xCA);
  TWI_WRREG(0x36, 0xEB);
  TWI_WRREG(0x37, 0x37);
  TWI_WRREG(0x38, 0x82);

  TWI_WRREG(0x12, 0x10); //vEnableRegMode step 5
  TWI_WRREG(0x12, 0x00);
  TWI_WRREG(0x24, 0x07);
  TWI_WRREG(0x1D, 0x20);

  //program the RAM config
  for(int i = 0; i <CMTNUMREGS; i++)
  {
    TWI_RAM1(i,cmtReg[i]);
  }

  TWI_WRREG(0x0D, 0x02); //step 7 send the TWI_OFF command. Control reverts to simple DAT signals

  digitalWrite(GPIO_SPI_DATA, HIGH);                 //output on
  usleep(2);
}


//Reads the CMT2119A's own on-chip EEPROM back into cmtReg[], so a chip that
//was already programmed (its EEPROM burned, e.g. via 'P' on this or another
//unit) can have its settings read into this programmer. This reuses the same
//TWI_EEPROM_SETUP()/TWI_EEPROM_READ()/TWI_EEPROM_END() sequence that
//cmtEepromBurn() already uses to verify its own writes, rather than
//inventing a new, unverified RAM-register read protocol.

void cmtReadFromChip(void)
{
  TWI_reset();
  TWI_reset();
  TWI_EEPROM_SETUP();
  for(int r = 0; r <0x15; r++)           //read EEPROM values 0x00 - 0x14
  {
    cmtReg[r] = TWI_EEPROM_READ(r);
  }

  uint16_t bytes[4];                   // for reading in the Ref Oscillator value

  for(int r = 0x15; r < 0x19; r++)     //read EEPROM values 0x15 - 0x18
  {
    bytes[r - 0x15] = TWI_EEPROM_READ(r);
  }

  memcpy(&refOsc, bytes, sizeof(refOsc));

  if((refOsc < 25.00) | (refOsc > 27.00))
  {
    printf("Setting Default Ref Osc = 26 MHz\n");
    refOsc = 26.00;
  }

  TWI_EEPROM_END();

  CMT2119A_RESET();
  digitalWrite(GPIO_SPI_DATA,HIGH);
}


double cmtGetPfd(void)
{
  double pfd = refOsc / 131072.0 ;
  return pfd;
}

void cmtSetFrequency(double direct)
{
  double freq;
  double pfd;
  uint8_t prescale15;
  uint8_t prescale2;

  pfd = cmtGetPfd();

  freq = direct;

  if(freq <= 320.0)
  {
    prescale15 = 1;
    prescale2 = 1;
  }
  else if(freq <= 480.0)
  {
    prescale15 = 0;
    prescale2 = 1;
  }
  else if(freq <= 640.0)
  {
    prescale15 = 1;
    prescale2 = 0;
  }
  else
  {
    prescale15 = 0;
    prescale2 = 0;
  }

  if(prescale15) cmtReg[6] = 1; else cmtReg[6] = 0;
  if(prescale2) cmtReg[1] = 0x5400; else cmtReg[1] = 0x5000;

  if(prescale15) freq = freq * 1.5;
  if(prescale2) freq = freq *2.0;

  //frequency
  uint32_t pll = round((freq/pfd)/2) *2;                //round to nearest even number
  cmtReg[7] = pll & 0xfffe;              //lsb must always be zero.
  uint16_t pllh = (pll >> 8) & 0xFF00;
  cmtReg[8] = pllh;
  cmtReg[9] = 0;
}


void cmtCalcFreq(void)
{
  uint8_t prescale15;
  uint8_t prescale2;
  uint32_t divider;
  double vco;
  double pfd;
  double diva;

  prescale15 = cmtReg[6] & 0x01;
  prescale2 = (cmtReg[1] & 0x0400) >> 10;
  divider = ((cmtReg[8] & 0xFF00) << 8) + cmtReg[7];
  pfd = cmtGetPfd();

  vco = (double) divider * pfd;
  diva=1;
  if(prescale2) diva = diva * 2;
  if(prescale15) diva=diva * 1.5;


  printf("\nChip type is CMT2119A\n");
  printf("Reference Oscillator = %2.f MHz\n", refOsc);
  printf("Step Size = %f Hz\n", pfd * 2000000); //double the step size to allow for the fact the divider must be even.
  printf("N = %d\n", divider / 2);              //halve the divider to allow for the fact it must be even.
  printf("VCO = %f MHz\n", vco);
  printf("O/P Divider = %f\n", diva);
  printf("Output Frequency = %f MHz\n", vco / diva);
}


double cmtGetFrequency(void)
{
  uint8_t prescale15;
  uint8_t prescale2;
  uint32_t divider;
  double vco;
  double pfd;
  double diva;

  prescale15 = cmtReg[6] & 0x01;
  prescale2 = (cmtReg[1] & 0x0400) >> 10;
  divider = ((cmtReg[8] & 0xFF00) << 8) + cmtReg[7];
  pfd = cmtGetPfd();

  vco = (double) divider * pfd;
  diva=1;
  if(prescale2) diva = diva * 2;
  if(prescale15) diva=diva * 1.5;

  return vco/diva;
}


void TWI_reset(void)
{
  digitalWrite(GPIO_SPI_DATA, LOW);
  digitalWrite(GPIO_SPI_CLK, HIGH);
  usleep(1);

  for(uint8_t i = 0; i < 32; ++i)
  {
    digitalWrite(GPIO_SPI_CLK, LOW);
    usleep(10);
    digitalWrite(GPIO_SPI_CLK, HIGH);
    usleep(10);
  }

  TWI_WRREG(0x0d, 0x00);
}



/***************************************************************************//**
 * @brief Writes a character to spi
 *        
 * @param uint8_t x charcater to be written
 *
 * @return void
*******************************************************************************/
void TWI_Write(uint8_t x)
{
  digitalWrite(GPIO_SPI_CLK, HIGH);
  digitalWrite(GPIO_SPI_DATA, LOW);

  for (uint8_t i = 0; i < 8; ++i)
  {
    digitalWrite(GPIO_SPI_CLK, HIGH);
    
    if (x & 0x80)
    {
      digitalWrite(GPIO_SPI_DATA, HIGH);
    }
    else
    {
      digitalWrite(GPIO_SPI_DATA, LOW);
    }
    usleep(10);
    digitalWrite(GPIO_SPI_CLK, LOW);
    usleep(10);
    x<<=1;
  }
  digitalWrite(GPIO_SPI_CLK, HIGH);
  digitalWrite(GPIO_SPI_DATA, LOW);
}


/***************************************************************************//**
 * @brief Reads a character from spi
 *        
 * @param nil
 *
 * @return uint8_t character read from spi
*******************************************************************************/
uint8_t TWI_Read(void)
{
  uint8_t r = 0;
  pinMode(GPIO_SPI_DATA,INPUT);
  digitalWrite(GPIO_SPI_CLK, HIGH);

  for (uint8_t i = 0; i < 8; ++i)
  {
    digitalWrite(GPIO_SPI_CLK, HIGH);
    usleep(10);
    r<<=1;
    digitalWrite(GPIO_SPI_CLK, LOW);
    usleep(10);
    if (digitalRead(GPIO_SPI_DATA))
    {
      r|=1;
    }
  }
  digitalWrite(GPIO_SPI_CLK, HIGH);
  pinMode(GPIO_SPI_DATA, OUTPUT);
  digitalWrite(GPIO_SPI_DATA, LOW);
  return r;
}


/***************************************************************************//**
 * @brief Writes to register "addr" with "data"
 *        
 * @param uint8_t addr, uint8_t data
 *
 * @return nil
*******************************************************************************/
void TWI_WRREG(uint8_t addr, uint8_t data)
{
  TWI_Write(0x80|(addr&0x3f));
  TWI_Write(data);
}


/***************************************************************************//**
 * @brief Reads from register "addr" and returns value
 *        
 * @param uint8_t addr
 *
 * @return uint8_t data
*******************************************************************************/
uint8_t TWI_RDREG(uint8_t addr)
{
  TWI_Write(0xc0|(addr&0x3f));
  return TWI_Read();
}


void TWI_RAM1(uint8_t addr, uint16_t data)
{
  TWI_WRREG(0x18, addr);
  TWI_WRREG(0x19, data&0xff);
  TWI_WRREG(0x1A, data>>8);
  TWI_WRREG(0x25, 0x01);
}


void TWI_EEPROM_ERASE(uint8_t add)
{
  uint8_t resp;
  TWI_WRREG(0x17,add);            // Set the EEPROM Address
  TWI_WRREG(0x16,0x39);           // start the erase
  do                              // wait till the erase has completed
  {
    usleep(1000);
    resp = TWI_RDREG(0x1F);
  }
  while ((resp & 0x08) == 0);
  TWI_WRREG(0x16,0x31);           // end the erase
}


void TWI_EEPROM_WRITE(uint8_t add, uint16_t dat)
{
  uint8_t resp;
  TWI_WRREG(0x17,add);          //Set the EEPROM Address
  TWI_WRREG(0x19,dat & 0xFF);   //Set the EEPROM Low Byte
  TWI_WRREG(0x1A,dat >> 8);     //Set the EEPROM High Byte
  TWI_WRREG(0x16,0x35);         //start the write
  do                            //wait till the erase has completed
   {
    usleep(1000);
    resp = TWI_RDREG(0x1F);
   }
  while ((resp & 0x08) == 0);
  TWI_WRREG(0x16,0x31);           //end the write
}


uint16_t TWI_EEPROM_READ(uint8_t add)
{
  uint8_t resp;
  uint16_t val;
  TWI_WRREG(0x17,add);          //Set the EEPROM Address
  TWI_WRREG(0x16,0x33);         //start the read
  do                            //wait till the erase has completed
   {
    usleep(1000);
    resp = TWI_RDREG(0x1F);
   }
  while ((resp & 0x08) == 0);
  val =(TWI_RDREG(0x1C) <<8) + TWI_RDREG(0x1B) ;
  TWI_WRREG(0x16,0x31);           //end the read
  return val;
}


void TWI_EEPROM_SETUP(void)
{
    TWI_WRREG(0x02,0x3B);
    TWI_WRREG(0x2F,0x80);
    TWI_WRREG(0x3F,0x01);
    TWI_WRREG(0x16,0x31);
    TWI_WRREG(0x35,0xCA);
    TWI_WRREG(0x36,0xEB);
    TWI_WRREG(0x37,0x37);
    TWI_WRREG(0x38,0x82);
}


void TWI_EEPROM_END(void)
{
    TWI_WRREG(0x16,0x30);
    TWI_WRREG(0x3F,0x00);
    TWI_WRREG(0x0C,0x27);
    TWI_WRREG(0x2F,0x00);
    TWI_WRREG(0x02,0x7F);
    TWI_WRREG(0x0C,0x00);
    TWI_WRREG(0x3D,0x01);         //SOFT_RESET.
}


//Burn the chip's built-in EEPROM. Sequence copied originally from the official
//programmer and then trimmed. This is a CMT2119A hardware feature (the chip can
//store its own power-up configuration), not a modulation mode, so it is retained.

void cmtEepromBurn(void)
{
  printf("Burn and Verify Start\n");
  TWI_reset();
  TWI_reset();
  TWI_EEPROM_SETUP();
  for(int r=0; r < 0x15; r++)           //erase and write EEPROM values 0x00 - 0x14
  {
    TWI_EEPROM_ERASE(r);
    TWI_EEPROM_WRITE(r, cmtReg[r]);
  }

  // Use 4 unused? EEPROM locations to save the Reference Oscillator frequency

  uint16_t bytes[4];         //for conversion of Double to 4x Uint16_t
  memcpy(bytes, &refOsc, sizeof(refOsc));

  TWI_EEPROM_ERASE(0x15);
  TWI_EEPROM_WRITE(0x15,bytes[0]);
  TWI_EEPROM_ERASE(0x16);
  TWI_EEPROM_WRITE(0x16,bytes[1]);
  TWI_EEPROM_ERASE(0x17);
  TWI_EEPROM_WRITE(0x17,bytes[2]);
  TWI_EEPROM_ERASE(0x18);
  TWI_EEPROM_WRITE(0x18,bytes[3]);

  for(int r=0; r < 0x15; r++)           //verify the EEPROM values 0x00 - 0x14
  {
    uint16_t val = TWI_EEPROM_READ(r);
    if (val!= cmtReg[r])
    {
      printf("Verify Error at address = %X Value = %X\n", r, val);
    }
  }

  //verify the additional EEPROM locations
  for(int r = 0x15; r < 0x19; r++)           //verify the EEPROM values 0x15 - 0x18
  {
    uint16_t val = TWI_EEPROM_READ(r);
    if (val!= bytes[r-0x15])
    {
      printf("RefOsc Verify Error at address = %X Value = %X\n", r, val);
    }
  }

  TWI_EEPROM_END();
  printf("Burn and Verify Complete\n");

  printf("Resetting from CMT2119A EEPROM\n");
  CMT2119A_RESET();
  digitalWrite(GPIO_SPI_DATA, HIGH);
}

